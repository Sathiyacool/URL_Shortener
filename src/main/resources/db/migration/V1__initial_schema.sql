CREATE TABLE short_urls (
    code VARCHAR(32) NOT NULL PRIMARY KEY,
    destination_url VARCHAR(2048) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE url_clicks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code VARCHAR(32) NOT NULL,
    clicked_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    referrer VARCHAR(2048),
    user_agent VARCHAR(512)
);
CREATE INDEX idx_url_clicks_code_time ON url_clicks (short_code, clicked_at);

CREATE TABLE orchestration_runs (
    id UUID NOT NULL PRIMARY KEY,
    scenario_id VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    input_summary VARCHAR(4000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    audit_sequence BIGINT NOT NULL,
    audit_hash VARCHAR(64) NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE orchestration_tasks (
    id UUID NOT NULL PRIMARY KEY,
    run_id UUID NOT NULL,
    task_key VARCHAR(100) NOT NULL,
    task_kind VARCHAR(32) NOT NULL,
    impact_level VARCHAR(16) NOT NULL,
    state VARCHAR(32) NOT NULL,
    attempt_count INTEGER NOT NULL,
    result_summary VARCHAR(4000),
    failure_summary VARCHAR(4000),
    retired BOOLEAN NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uk_orchestration_task_run_key UNIQUE (run_id, task_key)
);

CREATE TABLE orchestration_task_dependencies (
    task_execution_id UUID NOT NULL,
    dependency_task_key VARCHAR(100) NOT NULL,
    CONSTRAINT pk_orchestration_task_dependencies
        PRIMARY KEY (task_execution_id, dependency_task_key)
);

CREATE TABLE orchestration_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    event_sequence BIGINT NOT NULL,
    task_key VARCHAR(100),
    event_type VARCHAR(32) NOT NULL,
    actor_type VARCHAR(16) NOT NULL,
    actor_reference VARCHAR(128) NOT NULL,
    previous_value VARCHAR(64),
    new_value VARCHAR(64),
    details VARCHAR(4000),
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    previous_hash VARCHAR(64) NOT NULL,
    event_hash VARCHAR(64) NOT NULL,
    CONSTRAINT uk_orchestration_event_run_sequence UNIQUE (run_id, event_sequence)
);
CREATE INDEX idx_orchestration_events_run_time ON orchestration_events (run_id, occurred_at);
CREATE INDEX idx_orchestration_events_run_sequence ON orchestration_events (run_id, event_sequence);

CREATE TABLE orchestration_decisions (
    id UUID NOT NULL PRIMARY KEY,
    run_id UUID NOT NULL,
    task_key VARCHAR(100),
    parent_decision_id UUID,
    decision_kind VARCHAR(24) NOT NULL,
    actor_type VARCHAR(16) NOT NULL,
    actor_reference VARCHAR(128) NOT NULL,
    input_summary VARCHAR(4000),
    rationale VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_orchestration_decisions_run_time ON orchestration_decisions (run_id, created_at);

CREATE TABLE approval_requests (
    id UUID NOT NULL PRIMARY KEY,
    run_id UUID NOT NULL,
    task_key VARCHAR(100) NOT NULL,
    impact_level VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    request_summary VARCHAR(1000) NOT NULL,
    request_decision_id UUID NOT NULL,
    decision_record_id UUID,
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP(6) WITH TIME ZONE,
    approver VARCHAR(128),
    decision_rationale VARCHAR(4000),
    version BIGINT NOT NULL
);
CREATE INDEX idx_approval_status_requested ON approval_requests (status, requested_at);
CREATE INDEX idx_approval_run_task ON approval_requests (run_id, task_key, requested_at);

CREATE TABLE artifact_versions (
    id UUID NOT NULL PRIMARY KEY,
    run_id UUID NOT NULL,
    task_key VARCHAR(100) NOT NULL,
    artifact_path VARCHAR(512) NOT NULL,
    version_number INTEGER NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    content TEXT NOT NULL,
    change_summary VARCHAR(1000) NOT NULL,
    decision_record_id UUID NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_artifact_run_path_version UNIQUE (run_id, artifact_path, version_number)
);
CREATE INDEX idx_artifact_run_task ON artifact_versions (run_id, task_key, created_at);
